#!/usr/bin/env python3
"""Pull the upstream ArduPilot data this project is built on.

What it does:
  1. Sparse-clones github.com/ArduPilot/ardupilot at --ref
     (default: ArduCopter-stable) into a work directory.
  2. Copies Tools/Frame_params/ (per-airframe parameter files contributed
     by users and manufacturers) into data/upstream/frame_params/,
     unmodified, together with ArduPilot's GPL-3.0 licence text.
  3. Runs ArduPilot's own Tools/autotest/param_metadata/param_parse.py to
     generate the ArduCopter parameter documentation, and stores a
     flattened copy at data/upstream/copter_params.json.
  4. Records exactly which commit everything came from in
     data/upstream/SOURCE.json (used for attribution in the docs).

Requires git and Python 3.11+.

SPDX-License-Identifier: GPL-3.0-or-later
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from apparams import FRAME_PARAMS_DIR, METADATA_FILE, SOURCE_FILE, UPSTREAM_DIR  # noqa: E402

UPSTREAM_URL = "https://github.com/ArduPilot/ardupilot.git"
SPARSE_PATHS = [
    "Tools/Frame_params",
    "Tools/autotest/param_metadata",
    "ArduCopter",
    "libraries",
    "COPYING.txt",
]
# Groups that only matter inside the simulator.
SKIP_PREFIXES = ("SIM_",)


def run(cmd: list[str], cwd: Path | None = None) -> str:
    print("+", " ".join(cmd), flush=True)
    res = subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True)
    return res.stdout.strip()


def clone(ref: str, dest: Path) -> None:
    if (dest / ".git").exists():
        run(["git", "fetch", "--depth", "1", "origin", ref], cwd=dest)
        run(["git", "checkout", "--force", "FETCH_HEAD"], cwd=dest)
    else:
        run(["git", "clone", "--depth", "1", "--filter=blob:none", "--sparse",
             "--branch", ref, UPSTREAM_URL, str(dest)])
    run(["git", "sparse-checkout", "set", "--no-cone", *SPARSE_PATHS], cwd=dest)


def build_metadata(clone_dir: Path) -> dict:
    meta_dir = clone_dir / "Tools" / "autotest" / "param_metadata"
    out = meta_dir / "apm.pdef.json"
    out.unlink(missing_ok=True)
    run([sys.executable, "param_parse.py", "--vehicle", "ArduCopter",
         "--format", "json"], cwd=meta_dir)
    with out.open(encoding="utf-8") as f:
        grouped = json.load(f)

    flat: dict[str, dict] = {}
    for group, params in grouped.items():
        if group == "json":
            continue
        for name, meta in params.items():
            if name.startswith(SKIP_PREFIXES):
                continue
            entry = dict(meta)
            # The unnamed group holds parameters defined by Lua scripting
            # applets; mark them so the docs can say so.
            entry["Group"] = group or "scripting-applet"
            flat[name] = entry
    return flat


def firmware_version(clone_dir: Path) -> str:
    vh = clone_dir / "ArduCopter" / "version.h"
    for line in vh.read_text(encoding="utf-8").splitlines():
        if "THISFIRMWARE" in line and '"' in line:
            return line.split('"')[1]
    return "unknown"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ref", default="ArduCopter-stable",
                    help="upstream tag or branch, e.g. ArduCopter-stable, "
                         "Copter-4.6.3, master (default: %(default)s)")
    ap.add_argument("--workdir", type=Path, default=None,
                    help="where to keep the sparse clone (default: a temp dir, "
                         "deleted afterwards)")
    args = ap.parse_args()

    tmp = None
    if args.workdir:
        clone_dir = args.workdir.resolve()
    else:
        tmp = tempfile.TemporaryDirectory(prefix="ardupilot-")
        clone_dir = Path(tmp.name) / "ardupilot"

    try:
        clone(args.ref, clone_dir)
        commit = run(["git", "rev-parse", "HEAD"], cwd=clone_dir)
        commit_date = run(["git", "log", "-1", "--format=%cI"], cwd=clone_dir)
        version = firmware_version(clone_dir)

        # 1. Frame parameter files, copied unmodified.
        if FRAME_PARAMS_DIR.exists():
            shutil.rmtree(FRAME_PARAMS_DIR)
        shutil.copytree(clone_dir / "Tools" / "Frame_params", FRAME_PARAMS_DIR)
        UPSTREAM_DIR.mkdir(parents=True, exist_ok=True)
        shutil.copy2(clone_dir / "COPYING.txt", UPSTREAM_DIR / "ARDUPILOT_LICENSE.txt")

        # 2. Parameter documentation generated by ArduPilot's own tool.
        flat = build_metadata(clone_dir)
        with METADATA_FILE.open("w", encoding="utf-8") as f:
            json.dump({
                "generated_by": "ArduPilot Tools/autotest/param_metadata/param_parse.py",
                "vehicle": "ArduCopter",
                "firmware": version,
                "params": dict(sorted(flat.items())),
            }, f, indent=1, ensure_ascii=False)
            f.write("\n")

        # 3. Provenance.
        source = {
            "repository": "https://github.com/ArduPilot/ardupilot",
            "ref": args.ref,
            "commit": commit,
            "commit_date": commit_date,
            "firmware": version,
            "fetched_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
            "paths": SPARSE_PATHS,
            "license": "GPL-3.0 (see data/upstream/ARDUPILOT_LICENSE.txt)",
        }
        with SOURCE_FILE.open("w", encoding="utf-8") as f:
            json.dump(source, f, indent=2)
            f.write("\n")

        n_files = sum(1 for p in FRAME_PARAMS_DIR.rglob("*") if p.is_file())
        print(f"\nDone: {version} @ {commit[:10]} ({args.ref})")
        print(f"  {len(flat)} parameters documented -> {METADATA_FILE}")
        print(f"  {n_files} files copied        -> {FRAME_PARAMS_DIR}")
    finally:
        if tmp:
            tmp.cleanup()


if __name__ == "__main__":
    main()
